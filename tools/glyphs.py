"""Atlas de glyphes ASCII (du plus clair au plus dense) pour la carte « Code source »."""
from PIL import Image

G = [
    ["........"] * 8,
    ["........", "........", "........", "........", "........", "...##...", "...##...", "........"],
    ["........", "...##...", "...##...", "........", "........", "...##...", "...##...", "........"],
    ["........", "........", "........", ".######.", ".######.", "........", "........", "........"],
    ["........", "........", ".######.", "........", "........", ".######.", "........", "........"],
    ["........", "...##...", "...##...", ".######.", ".######.", "...##...", "...##...", "........"],
    ["........", ".#.##.#.", "..####..", ".######.", "..####..", ".#.##.#.", "........", "........"],
    ["..#..#..", ".######.", "..#..#..", "..#..#..", ".######.", "..#..#..", "........", "........"],
    [".##...#.", ".##..#..", "....#...", "...#....", "..#..##.", ".#...##.", "........", "........"],
    ["..####..", ".#....#.", ".#.###.#", ".#.#.#.#", ".#.####.", ".#......", "..#####.", "........"],
]
img = Image.new('RGBA', (8 * len(G), 8), (0, 0, 0, 255))
for gi, rows in enumerate(G):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '#':
                img.putpixel((gi * 8 + x, y), (255, 255, 255, 255))
img.save('/home/claude/fate-flip/src/main/resources/assets/fateflip/textures/misc/ascii_glyphs.png')
print('ok')
